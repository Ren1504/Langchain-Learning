def output_parsers():
    """
    Demonstrates extracting strictly typed data using:
    1. PydanticOutputParser: Uses prompt instructions + schema parsing.
    2. Model-native Structured Output (`with_structured_output`):
       Leverages model function-calling / JSON schema constraints directly.
    """
    print("\n--- 11. Structured Output and Pydantic Parsers ---")

    # Define Pydantic models for expected schemas
    class Person(BaseModel):
        name: str = Field(description="Name of the person")
        age: int = Field(description="Age of the person")
        occupation: str = Field(description="Job or profession of the person")

    class MovieReview(BaseModel):
        title: str = Field(description="Name of the movie")
        review: str = Field(description="Review summary of the movie")
        rating: float = Field(description="Rating of the movie out of 10")

    # Approach A: PydanticOutputParser (works across any LLM via format instructions)
    parser = PydanticOutputParser(pydantic_object=Person)

    prompt = ChatPromptTemplate.from_template(
        "Extract details from this bio:\n{description}\n\n{format_instructions}"
    ).partial(format_instructions=parser.get_format_instructions())

    model = init_chat_model(model="gemini-2.5-flash", model_provider="google_genai", temperature=0)

    chain = prompt | model | parser
    person_result = chain.invoke(
        {"description": "Marie is a 22 year old who is working as a Marketing intern at Microsoft"}
    )
    print(f"Pydantic Parsed Object: {person_result}")
    print(f"  Name: {person_result.name}, Age: {person_result.age}, Job: {person_result.occupation}\n")

    # Approach B: Native with_structured_output (Recommended for modern models)
    structured_model = model.with_structured_output(MovieReview)
    review_result = structured_model.invoke(
        "Review: Odyssey is a great film by Nolan, would give a solid 9.5/10"
    )
    print(f"Native Structured Output Object: {review_result}")
    print(f"  Title: {review_result.title}, Rating: {review_result.rating}/10")


