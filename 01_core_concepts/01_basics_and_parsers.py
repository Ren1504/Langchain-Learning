"""
01_basics_and_parsers.py
========================
Module: Core Concepts - LangChain Basics, Models, Prompts, and Output Parsers

This module introduces the fundamental building blocks of LangChain:
1. Initializing Chat Models (Google Gemini & OpenAI via init_chat_model).
2. Constructing Prompts (ChatPromptTemplate, FewShotChatMessagePromptTemplate).
3. LangChain Expression Language (LCEL) syntax: `prompt | model | parser`.
4. Execution Modes: Single Invocation (`invoke`), Batching (`batch`), and Streaming (`stream`).
5. Schema Inspection: Examining input and output JSON schemas of runnables.
6. Structured Output and Parsers:
   - StrOutputParser (raw string)
   - JsonOutputParser (JSON dictionary)
   - PydanticOutputParser (strongly typed objects with validation)
   - `.with_structured_output()` (native model-level schema enforcement)

Prerequisites:
- Set GOOGLE_API_KEY or OPENAI_API_KEY in your `.env` file.
"""

from dotenv import load_dotenv
from langchain_google_genai import ChatGoogleGenerativeAI
from langchain_core.prompts import ChatPromptTemplate, FewShotChatMessagePromptTemplate
from langchain_core.output_parsers import StrOutputParser, JsonOutputParser, PydanticOutputParser
from langchain.chat_models import init_chat_model
from langchain_core.messages import HumanMessage, SystemMessage, AIMessage
from pydantic import BaseModel, Field

# Load environment variables (.env file containing API keys)
load_dotenv()


# ============================================================================
# 1. BASIC LCEL CHAIN & EXECUTION MODES
# ============================================================================

def demo_basic_chain():
    """
    Demonstrates the simplest LCEL (LangChain Expression Language) chain:
        Prompt -> Model -> Output Parser
    
    The pipe operator `|` connects components:
    - `prompt`: Transforms an input dictionary into a list of messages.
    - `model`: Sends the messages to Gemini and returns an AIMessage.
    - `parser`: Extracts the clean string content from the AIMessage.
    """
    print("\n--- 1. Basic LCEL Chain (Batch Invocation) ---")

    # 1. Define Prompt Template with a {question} placeholder
    prompt = ChatPromptTemplate.from_template(
        "You are a helpful assistant. Answer in one sentence: {question}"
    )

    # 2. Instantiate the Chat Model (Gemini 2.5 Flash)
    model = ChatGoogleGenerativeAI(model="gemini-2.5-flash", temperature=0.7)

    # 3. Parse output as plain string
    parser = StrOutputParser()

    # 4. Compose the chain using the pipe operator |
    chain = prompt | model | parser

    # Batch execution: Process multiple inputs concurrently in a single call
    inputs = [
        {"question": "Who is the prime minister of India?"},
        {"question": "Who won Game of the Year in 2020?"}
    ]

    print("Running batch inputs...")
    results = chain.batch(inputs)

    for item, result in zip(inputs, results):
        print(f"  Input: {item['question']}")
        print(f"  Output: {result}\n")


def demo_streaming():
    """
    Demonstrates real-time token streaming.
    Instead of waiting for the full response, `chain.stream()` yields chunks
    as they are generated by the model. Ideal for interactive UIs.
    """
    print("\n--- 2. Streaming Output Demonstration ---")

    prompt = ChatPromptTemplate.from_template("Write a haiku about {topic}")
    model = ChatGoogleGenerativeAI(model="gemini-2.5-flash", temperature=0.7)
    parser = StrOutputParser()

    chain = prompt | model | parser

    print("Streaming haiku about 'nature':\n")
    # chain.stream() yields tokens incrementally
    for chunk in chain.stream({"topic": "nature"}):
        print(chunk, end="", flush=True)
    print("\n")


def demo_schema_inspection():
    """
    Demonstrates how LCEL runnables expose their expected input and output schemas.
    This helps with debugging, automated UI generation, and validating pipelines.
    """
    print("\n--- 3. Schema Inspection ---")

    prompt = ChatPromptTemplate.from_template("Write a haiku about {topic}")
    model = ChatGoogleGenerativeAI(model="gemini-2.5-flash", temperature=0.7)
    parser = StrOutputParser()

    chain = prompt | model | parser

    # Inspect the expected input schema (expects a dictionary with key 'topic')
    input_schema = chain.input_schema.model_json_schema()
    # Inspect the generated output schema (produces a string)
    output_schema = chain.output_schema.model_json_schema()

    print(f"Expected Input Schema: {input_schema}")
    print(f"Generated Output Schema: {output_schema}")


def product_chain():
    """
    Example of a single-input chain producing a marketing tagline.
    """
    print("\n--- 4. Product Tagline Chain ---")

    prompt = ChatPromptTemplate.from_template(
        "Write a catchy product tagline for this product: {product}"
    )
    model = ChatGoogleGenerativeAI(model="gemini-2.5-flash", temperature=0.7)
    parser = StrOutputParser()

    product_name = "Game Boy"
    chain = prompt | model | parser

    result = chain.invoke({"product": product_name})
    print(f"Product: {product_name} => Tagline: {result}")


