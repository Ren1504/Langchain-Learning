def prompt_messages():
    """
    Demonstrates formatting a ChatPromptTemplate with dynamic placeholders.
    """
    print("\n--- 8. Basic ChatPromptTemplate Formatting ---")

    prompt = ChatPromptTemplate.from_template("Recommend me a game of {genre} about {topic}")
    messages = prompt.format_messages(genre="Adventure", topic="Monsters")
    print(f"Formatted Messages: {messages}")


def multi_prompt():
    """
    Demonstrates structured multi-role prompts with (role, template) tuples.
    Allows injecting dynamic parameters into system prompts as well as user messages.
    """
    print("\n--- 9. Multi-Role Prompt Template ---")

    prompt = ChatPromptTemplate.from_messages(
        [
            ("system", "You are a translator that translates {input} to {output}."),
            ("human", "Translate this text: {text}")
        ]
    )

    formatted_messages = prompt.format_messages(
        input="English",
        output="Tamil",
        text="I am going to the market"
    )

    model = ChatGoogleGenerativeAI(model="gemini-2.5-flash", temperature=0.7)
    response = model.invoke(formatted_messages)

    print(f"Input: 'I am going to the market' -> Translated: {response.content}")


def few_shot():
    """
    Demonstrates Few-Shot Prompting using FewShotChatMessagePromptTemplate.
    Few-shot prompting provides in-context examples to guide the model's
    style, tone, or format without fine-tuning.
    """
    print("\n--- 10. Few-Shot Chat Prompt Template ---")

    # 1. Define example input-output pairs
    examples = [
        {"input": "happy", "output": "sad"},
        {"input": "big", "output": "small"},
    ]

    # 2. Template for how each example should be formatted
    example_prompt = ChatPromptTemplate.from_messages(
        [
            ("human", "{input}"),
            ("ai", "{output}")
        ]
    )

    # 3. Assemble the few-shot container
    few_shot_prompt = FewShotChatMessagePromptTemplate(
        example_prompt=example_prompt,
        examples=examples
    )

    # 4. Combine with the target query
    final_prompt = ChatPromptTemplate.from_messages(
        [
            ("system", "You are an antonym generator. Output only the antonym word."),
            few_shot_prompt,
            ("human", "{input}")
        ]
    )

    model = init_chat_model(model="gemini-2.5-flash", model_provider="google_genai", temperature=0.7)
    chain = final_prompt | model | StrOutputParser()

    result = chain.invoke({"input": "tall"})
    print(f"Antonym for 'tall': {result}")


