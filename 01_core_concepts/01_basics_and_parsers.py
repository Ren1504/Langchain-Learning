def demo_chat_model():
    """
    Demonstrates modern model initialization using `init_chat_model`.
    `init_chat_model` provides a provider-agnostic way to load models
    (OpenAI, Google GenAI, Anthropic, Ollama, etc.) with unified parameters.
    """
    print("\n--- 5. Provider-Agnostic init_chat_model ---")

    chat_model = init_chat_model(
        model="gemini-2.5-flash",
        model_provider="google_genai",
        temperature=0.7,
        streaming=True,
        max_retries=3,
    )

    response = chat_model.invoke("What is the capital of France?")
    print(f"Response: {response.content}")
    return chat_model


def demo_message():
    """
    Demonstrates low-level message interaction using explicit message objects:
    - SystemMessage: Sets model persona, guidelines, or tone.
    - HumanMessage: User queries.
    - AIMessage: Assistant responses.
    
    Shows how conversation state is manually preserved by appending past turns.
    """
    print("\n--- 6. Multi-Turn Conversation with Explicit Messages ---")

    model = ChatGoogleGenerativeAI(model="gemini-2.5-flash", temperature=0.7)

    # Initial context + question
    messages = [
        SystemMessage(content="Answer every question in an Aussie accent."),
        HumanMessage(content="How was the match yesterday?")
    ]

    response = model.invoke(messages)
    print(f"Turn 1 Response: {response.content}")

    # Append assistant's answer and user's follow-up to maintain context
    messages.append(response)
    messages.append(HumanMessage(content="What did I ask you before?"))

    response = model.invoke(messages)
    print(f"Turn 2 Response: {response.content}")


def exercise_multi_model():
    """
    Demonstrates comparing responses across multiple models or versions
    using a standardized loop and `init_chat_model`.
    """
    print("\n--- 7. Comparing Multiple Models ---")

    models = ["gemini-2.5-flash"]

    for model_name in models:
        chat_model = init_chat_model(
            model=model_name,
            model_provider="google_genai",
            temperature=0.7,
            streaming=True,
            max_retries=3,
        )

        response = chat_model.invoke("Write a sentence about pyramids.")
        print(f"[{model_name}]: {response.content}")


